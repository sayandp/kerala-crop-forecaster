const chat = schedule(conv.conversation as Entry[], 12, 0.55);
const ALERT_AT = chat.items.find((i) => i.text === "/alert നേന്ത്രൻ")!.typeFrom!;
const ceilBeat = (n: number) => Math.ceil(n / 18) * 18;

// Browser geometry (output px): 1360 px wide = 1440 CSS px of the recordings.
const BW = 1360;
const BS = BW / 1440;
const BX = (1920 - BW) / 2;
const BY = 30 + 58; // content top (below the address bar)
const out = (x: number, y: number) => ({ x: BX + x * BS, y: BY + y * BS });

// d-home.webm: the scroll reaches the banana cards at ~5.1 s and rests until 6.7 s
