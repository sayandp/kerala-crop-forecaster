const BotScene: React.FC = () => {
  const f = useCurrentFrame();
  const right = f < NOTIF ? "bullets" : f < CHANNEL ? "alert" : "channel";
  return (
    <AbsoluteFill>
      <div style={{ position: "absolute", left: 150, top: 28 }}>
        <Pop>
          <div style={{ padding: "10px 26px", borderRadius: 40, background: C.accent, color: "#fff", fontFamily: FONT_EN, fontWeight: 700, fontSize: 28 }}>
            Real replies from @keralacropprices_bot
          </div>
        </Pop>
      </div>
      <div style={{ position: "absolute", left: 150, top: 96 }}>
        <Chat items={chat.items} width={760} height={830} fs={24} title="കേരള വിപണി വില ബോട്ട്" />
      </div>
      <div style={{ position: "absolute", left: 1000, top: 96, width: 780, height: 830 }}>
        {right === "bullets" ? (
          <div style={{ display: "flex", flexDirection: "column", gap: 26, paddingTop: 110 }}>
            {BULLETS.map((x) =>
              f >= x.at ? (
                <Pop key={x.t} delay={x.at}>
                  <div style={{ display: "flex", gap: 20, alignItems: "flex-start" }}>
                    <div style={{ width: 16, height: 16, marginTop: 18, borderRadius: 8, background: C.accent, flex: "none" }} />
                    <div style={{ fontFamily: FONT_EN, fontSize: 40, fontWeight: 650, color: C.ink, lineHeight: 1.28 }}>{x.t}</div>
                  </div>
                </Pop>
              ) : null,
            )}
          </div>
        ) : right === "alert" ? (
          <div style={{ paddingTop: 200 }}>
            <Notification text={conv.alert_example.text} fs={28} width={780} delay={NOTIF + 4} />
          </div>
        ) : (
          <Pop delay={CHANNEL}>
            <ChannelPost text={conv.channel_post} width={780} height={830} fs={23} scroll={keys(f - CHANNEL, [[0, 0], [24, 0], [HZ.bot - CHANNEL - 14, 1500]])} />
          </Pop>
        )}
      </div>
    </AbsoluteFill>
  );
};

